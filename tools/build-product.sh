set -eu
cd "$(dirname "$0")/.."
# Start from an empty bundle, so a build without private inputs never keeps an earlier epicycle/ROM/Tools
# and codesign never meets a stale file's extended attributes.
rm -rf build/Ptolemy.app
mkdir -p build/product/modules build/Ptolemy.app/Contents/MacOS build/Ptolemy.app/Contents/Resources
swiftc -swift-version 5 -target arm64-apple-macos26 -O -module-cache-path "$PWD/build/product/modules" product/InstallCore.swift product/Launcher.swift product/PtolemyApp.swift product/SelfTest.swift product/main.swift -framework AppKit -framework CryptoKit -framework IOKit -framework DiskArbitration -o build/Ptolemy.app/Contents/MacOS/Ptolemy
cp product/Info.plist build/Ptolemy.app/Contents/Info.plist
icons=assets; [ -d "$icons" ] || icons=../../assets   # the icon and launcher art: assets/ in the repository
if test -f "$icons/app-icon-macos-1024.png";then
  tmp=$(mktemp -d);set="$tmp/Ptolemy.iconset";mkdir -p "$set"
  for s in 16 32 128 256 512;do
    sips -z $s $s "$icons/app-icon-macos-1024.png" --out "$set/icon_${s}x${s}.png" >/dev/null
    sips -z $((s*2)) $((s*2)) "$icons/app-icon-macos-1024.png" --out "$set/icon_${s}x${s}@2x.png" >/dev/null
  done
  iconutil -c icns "$set" -o build/Ptolemy.app/Contents/Resources/Ptolemy.icns;rm -rf "$tmp"
fi
# The launcher's art (generated by assets/launcher-art.py; the mark from mark-transparent-1024.png).
for f in launcher-fur.jpg launcher-metal.jpg mark-glass.png;do if test -f "$icons/$f";then cp -X "$icons/$f" build/Ptolemy.app/Contents/Resources/;fi;done
# Private build inputs only; release packets contain no firmware, guest binary or image.
if [ -n "${PT_PRODUCT_ENGINE:-}" ]; then cp -X "$PT_PRODUCT_ENGINE" build/Ptolemy.app/Contents/Resources/ptolemy-engine; fi
if [ -n "${PT_PRODUCT_ROM:-}" ]; then cp -X "$PT_PRODUCT_ROM" build/Ptolemy.app/Contents/Resources/openbios-ppc; fi
if [ -n "${PT_PRODUCT_TOOLS:-}" ]; then cp -X "$PT_PRODUCT_TOOLS" build/Ptolemy.app/Contents/Resources/PtolemyTools.dmg; fi
codesign --force --sign - build/Ptolemy.app
if [ "${1:-}" = --test ]; then build/Ptolemy.app/Contents/MacOS/Ptolemy --self-test; fi
